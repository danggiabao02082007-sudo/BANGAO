// Chế độ TẮT quản lý tồn kho: node tests/browser/nostock.cjs <site> <ảnh>  (chạy sau khi đặt store_settings.track_stock = false)
const { chromium, devices } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const [site, out] = process.argv.slice(2);
const T = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.png': 'image/png', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml' };
const srv = http.createServer((q, r) => { let p = path.join(site, q.url.split('?')[0]); if (p.endsWith('/')) p += 'index.html';
  fs.readFile(p, (e, d) => { if (e) { r.writeHead(404); r.end(); } else { r.writeHead(200, { 'content-type': T[path.extname(p)] || 'text/plain' }); r.end(d); } }); }).listen(8781);
const res = []; const ok = (c, m) => { res.push([c, m]); console.log(c ? '  ✔' : '  ✘', m); };
const U = 'http://localhost:8781/';
(async () => {
  const b = await chromium.launch(); const errs = [];
  const p = await (await b.newContext({ ...devices['iPhone 13'] })).newPage();
  p.on('pageerror', e => errs.push(e.message));
  await p.route(/fonts\.(googleapis|gstatic)\.com/, r => r.abort());
  await p.goto(U); await p.fill('input[type=email]', 'chu@test.vn'); await p.fill('input[type=password]', 'Matkhau@123');
  await p.click('button:has-text("Đăng nhập")'); await p.waitForSelector('text=Doanh thu hôm nay', { timeout: 15000 }); await p.waitForTimeout(800);
  ok(await p.locator('text=Tồn kho').count() === 0 && await p.locator('text=Cảnh báo tồn thấp').count() === 0, 'Tổng quan không còn thẻ tồn kho / cảnh báo tồn');
  ok(await p.locator('nav >> text=Sản phẩm').count() >= 1 && await p.locator('nav >> text=Kho').count() === 0, 'Menu đổi "Kho" thành "Sản phẩm"');
  await p.screenshot({ path: `${out}/1_tong_quan.png` });
  await p.goto(U + '#products'); await p.waitForTimeout(1500);
  ok(await p.locator('text=Nhập tồn đầu kỳ').count() === 0 && await p.locator('text=Lịch sử kho').count() === 0 && await p.locator('text=Đối soát').count() === 0, 'Trang Sản phẩm ẩn nhập tồn, lịch sử kho, đối soát');
  ok(await p.locator('div.grid > button >> text=/^Tồn/').count() === 0, 'Thẻ mặt hàng không còn ô "Tồn"');
  await p.screenshot({ path: `${out}/2_san_pham.png` });
  await p.locator('div.grid > button').first().click(); await p.waitForTimeout(800);
  ok(await p.locator('text=Điều chỉnh kho').count() === 0 && await p.locator('text=Lô hàng còn tồn').count() === 0, 'Chi tiết mặt hàng ẩn lô và điều chỉnh kho');
  await p.keyboard.press('Escape');
  await p.goto(U + '#sales'); await p.waitForSelector('text=Chọn hàng'); await p.waitForTimeout(600);
  ok(await p.locator('text=/^Tồn:/').count() === 0, 'Bán hàng không hiện tồn kho');
  const btn = p.locator('button:has-text("+ Bao"):not([disabled])');
  const n = await btn.count();
  ok(n > 0, `Nút bán không bị khóa theo tồn kho (${n} nút + Bao)`);
  for (let i = 0; i < 3; i++) await btn.first().click();
  await p.locator('button:has-text("Lưu hóa đơn")').first().click();
  await p.waitForSelector('text=Đã lưu hóa đơn', { timeout: 10000 });
  ok(true, 'Lưu hóa đơn được dù mặt hàng không có tồn kho');
  await p.screenshot({ path: `${out}/3_da_ban.png` });
  ok(errs.length === 0, 'Không có lỗi JavaScript ' + JSON.stringify(errs));
  await b.close(); srv.close(); process.exit(res.every(x => x[0]) ? 0 : 1);
})().catch(e => { console.error(e); process.exit(1); });
